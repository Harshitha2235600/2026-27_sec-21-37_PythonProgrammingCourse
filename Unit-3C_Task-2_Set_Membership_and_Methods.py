
my_set = {1, 2, 3, 4, 5}
print("Original Set:", my_set)
# Checking membership
print("Is 4 in the set?", 4 in my_set)
print("Is 7 in the set?", 7 in my_set)
# Set methods
print("Length of the set:", len(my_set))
print("Maximum value in the set:", max(my_set))
print("Minimum value in the set:", min(my_set))
print("Sum of all elements in the set:", sum(my_set))